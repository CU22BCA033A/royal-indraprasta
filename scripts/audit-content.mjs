// Fails if the built site or the source breaks a content rule.
// Checks dist/ (what ships) and src/ comments and copy.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'dist');
const production = !process.env.DEMO;
const failures = [];
const fail = (where, msg) => failures.push(`${where}: ${msg}`);

function files(dir, test) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return f === 'node_modules' ? [] : files(p, test);
    return test(f) ? [p] : [];
  });
}

const EM_DASH = /—/;
const EN_DASH = /–/;
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{1F000}-\u{1F2FF}\u{1F900}-\u{1F9FF}\u{FE0F}]/u;
const BANNED_FONTS = /\b(Inter|Geist|Space Grotesk)\b/;
const BANNED_WORDS =
  /\b(elevate[sd]?|unlock(s|ed)?|seamless(ly)?|crafted with passion|experience the magic|culinary journey|lorem ipsum)\b/i;
const HYPE = /\b(best in bengaluru|best restaurant|no\. ?1|number one|award[- ]winning)\b/i;

// 1. Built HTML
const htmlFiles = files(dist, (f) => f.endsWith('.html'));
const titles = new Map();
const descs = new Map();
const year = String(new Date().getFullYear());
for (const file of htmlFiles) {
  const rel = relative(dist, file);
  const html = readFileSync(file, 'utf8');
  const text = html.replace(/<script[\s\S]*?<\/script>/g, '').replace(/<[^>]+>/g, ' ');
  if (EM_DASH.test(html)) fail(rel, 'contains an em dash');
  if (EN_DASH.test(text)) fail(rel, 'contains an en dash');
  if (EMOJI.test(text)) fail(rel, 'contains an emoji');
  if (/lorem/i.test(text)) fail(rel, 'contains lorem ipsum');
  if (production && /\b(TODO|PLACEHOLDER|NEEDS-NATIVE-REVIEW)\b/.test(html))
    fail(rel, 'contains a TODO or placeholder marker');
  if (BANNED_FONTS.test(html)) fail(rel, 'mentions a banned font');
  if (BANNED_WORDS.test(text)) fail(rel, `banned filler phrase: ${text.match(BANNED_WORDS)[0]}`);
  if (HYPE.test(text)) fail(rel, `unprovable claim: ${text.match(HYPE)[0]}`);
  if (/<meta[^>]+name="generator"/i.test(html)) fail(rel, 'generator meta tag');
  if (/made with ai|built with claude|generated by|powered by astro/i.test(text)) fail(rel, 'tool or AI credit');
  if (/aggregateRating|ratingValue/.test(html)) fail(rel, 'rating markup');
  for (const m of html.matchAll(/<img\b[^>]*>/g))
    if (!/\balt="/.test(m[0])) fail(rel, `image without alt: ${m[0].slice(0, 80)}`);
  for (const m of html.matchAll(/<(img|source)\b[^>]*\b(src|srcset)="(https?:)?\/\/[^"]+"/g))
    fail(rel, `remote image: ${m[0].slice(0, 80)}`);
  for (const m of html.matchAll(/href="tel:([^"]*)"/g))
    if (!/^\+\d{8,15}$/.test(m[1])) fail(rel, `malformed tel: ${m[1]}`);
  for (const m of html.matchAll(/href="mailto:([^"]*)"/g))
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(m[1])) fail(rel, `malformed mailto: ${m[1]}`);
  const c = html.match(/data-copyright>&copy; (\d{4})|data-copyright>© (\d{4})/);
  if (!/data-copyright/.test(html)) fail(rel, 'copyright line missing');
  else if (c && (c[1] ?? c[2]) !== year) fail(rel, `copyright year is not the build year`);
  const title = html.match(/<title>([^<]*)<\/title>/)?.[1];
  const desc = html.match(/<meta name="description" content="([^"]*)"/)?.[1];
  if (!title) fail(rel, 'no title');
  if (!desc) fail(rel, 'no description');
  if (title) {
    if (titles.has(title)) fail(rel, `duplicate title with ${titles.get(title)}`);
    titles.set(title, rel);
  }
  if (desc) {
    if (descs.has(desc)) fail(rel, `duplicate description with ${descs.get(desc)}`);
    descs.set(desc, rel);
  }
}

// 2. CSS and JS that ship
for (const file of files(dist, (f) => /\.(css|js)$/.test(f))) {
  const rel = relative(dist, file);
  if (rel.startsWith('pagefind')) continue;
  const s = readFileSync(file, 'utf8');
  if (EM_DASH.test(s)) fail(rel, 'contains an em dash');
  if (BANNED_FONTS.test(s)) fail(rel, 'mentions a banned font');
  if (/#fff(fff)?\b|#000(000)?\b/i.test(s)) fail(rel, 'pure white or pure black colour');
  if (/linear-gradient|radial-gradient|backdrop-filter/i.test(s)) fail(rel, 'gradient or glass effect');
  if (/cursor:\s*(none|url\()/i.test(s)) fail(rel, 'custom cursor');
}

// 3. Source: comments and copy must follow the same rules
for (const file of files(join(root, 'src'), (f) => /\.(ts|astro|css|json)$/.test(f))) {
  const rel = relative(root, file);
  const s = readFileSync(file, 'utf8');
  if (EM_DASH.test(s)) fail(rel, 'contains an em dash');
  if (EMOJI.test(s)) fail(rel, 'contains an emoji');
  if (/©\s*20\d\d|&copy;\s*20\d\d/.test(s)) fail(rel, 'hard-coded copyright year');
  if (/border-radius:\s*(?!\s|var\(--radius\)|0\b)/.test(s)) fail(rel, 'corner radius other than the 2px token');
}

if (failures.length) {
  console.error(`audit:content found ${failures.length} problem(s):`);
  for (const f of failures) console.error(`  ${f}`);
  process.exit(1);
}
console.log(`audit:content passed (${htmlFiles.length} pages, ${production ? 'production' : 'demo'} mode)`);
