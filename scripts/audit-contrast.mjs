// Computes WCAG 2.2 contrast for every text and UI token pair in both themes,
// writes docs/CONTRAST.md, and fails if any pair is below its threshold.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const css = readFileSync(join(root, 'src/styles/tokens.css'), 'utf8');

function block(selector) {
  const i = css.indexOf(selector);
  if (i < 0) throw new Error(`missing ${selector}`);
  const start = css.indexOf('{', i);
  const end = css.indexOf('}', start);
  const out = {};
  for (const m of css.slice(start, end).matchAll(/--([\w-]+):\s*(#[0-9a-f]{6})/gi)) out[m[1]] = m[2].toLowerCase();
  return out;
}
const themes = { light: block(':root {'), dark: block(":root[data-theme='dark']") };

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// [foreground, background, minimum, use]
const PAIRS = [
  ['text', 'bg', 7, 'Body text (AAA)'],
  ['text', 'surface', 7, 'Body text on panels (AAA)'],
  ['muted', 'bg', 4.5, 'Secondary text'],
  ['muted', 'surface', 4.5, 'Secondary text on panels'],
  ['primary', 'bg', 4.5, 'Links and buttons'],
  ['primary', 'surface', 4.5, 'Links on panels'],
  ['on-primary', 'primary', 4.5, 'Button label'],
  ['brass-ink', 'bg', 4.5, 'Small labels'],
  ['brass-ink', 'surface', 4.5, 'Small labels on panels'],
  ['veg', 'bg', 4.5, 'Veg mark and label'],
  ['veg', 'surface', 4.5, 'Veg mark on panels'],
  ['error', 'bg', 4.5, 'Error text'],
  ['error', 'surface', 4.5, 'Error text on panels'],
  ['line', 'bg', 3, 'Form field borders (non-text, 1.4.11)'],
  ['primary', 'bg', 3, 'Focus ring (non-text, 2.4.13)'],
  ['bg', 'text', 4.5, 'Hover state: page colour on text colour'],
  ['on-sign', 'sign', 7, 'Signboard text (AAA)'],
  ['on-sign-muted', 'sign', 4.5, 'Secondary text on the signboard'],
  ['brass', 'sign', 4.5, 'Brass labels and buttons on the signboard'],
  ['sign', 'brass', 4.5, 'Button label on brass'],
];
const DECORATIVE = [
  ['rule', 'bg', 'Hairline rules only, carries no information'],
  ['sign-rule', 'sign', 'Hairline rules on the signboard'],
];

let failed = 0;
const lines = [
  '# Contrast report',
  '',
  'Generated by `npm run audit:contrast` from `src/styles/tokens.css`. Thresholds: 7:1 for body text (AAA), 4.5:1 for other text (AA), 3:1 for borders and focus indicators.',
  '',
];
for (const [name, t] of Object.entries(themes)) {
  lines.push(
    `## ${name === 'light' ? 'Light' : 'Dark'} theme`,
    '',
    '| Foreground | Background | Ratio | Needs | Result | Use |',
    '|---|---|---|---|---|---|',
  );
  for (const [fg, bg, min, use] of PAIRS) {
    const r = ratio(t[fg], t[bg]);
    const ok = r >= min;
    if (!ok) failed++;
    lines.push(`| ${fg} ${t[fg]} | ${bg} ${t[bg]} | ${r.toFixed(2)}:1 | ${min}:1 | ${ok ? 'Pass' : 'FAIL'} | ${use} |`);
  }
  for (const [fg, bg, use] of DECORATIVE) {
    lines.push(
      `| ${fg} ${t[fg]} | ${bg} ${t[bg]} | ${ratio(t[fg], t[bg]).toFixed(2)}:1 | none | Decorative | ${use} |`,
    );
  }
  lines.push('');
}
writeFileSync(join(root, 'docs/CONTRAST.md'), lines.join('\n'));
if (failed) {
  console.error(`audit:contrast: ${failed} pair(s) below threshold. See docs/CONTRAST.md`);
  process.exit(1);
}
console.log(`audit:contrast passed (${PAIRS.length * 2} pairs), docs/CONTRAST.md written`);
