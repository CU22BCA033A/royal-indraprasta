// Bundles src/lib/vercel-handler.ts into api/_lib/handler.js for Vercel.
// `npm run api` writes it; `npm run api -- --check` fails if the committed
// bundle is out of date with the source.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const out = join(root, 'api/_lib/handler.js');
const result = await build({
  entryPoints: [join(root, 'src/lib/vercel-handler.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  conditions: ['edge-light', 'worker', 'browser'],
  legalComments: 'none',
  write: false,
  banner: { js: '// Generated by scripts/bundle-api.mjs from src/lib/vercel-handler.ts. Do not edit.' },
});
const code = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== code) {
    console.error('api/_lib/handler.js is out of date. Run `npm run api` and commit the result.');
    process.exit(1);
  }
  console.log('api bundle up to date');
} else {
  mkdirSync(join(root, 'api/_lib'), { recursive: true });
  writeFileSync(out, code);
  console.log(`api/_lib/handler.js written (${code.length} bytes)`);
}
